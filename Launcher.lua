local _, A = ...
function A.CreateLauncher()
    if A.launcher then return end
    local b=CreateFrame("Button","RaynnaNameplatesMinimapButton",Minimap)
    A.launcher=b
    b:SetSize(32,32)
    b:SetFrameStrata("MEDIUM")
    b:SetFrameLevel(Minimap:GetFrameLevel()+8)
    b.icon=b:CreateTexture(nil,"ARTWORK")
    b.icon:SetPoint("TOPLEFT",4,-4)
    b.icon:SetPoint("BOTTOMRIGHT",-4,4)
    b.icon:SetTexture('Interface\\Icons\\Ability_Hunter_HuntersMark')
    local ring=b:CreateTexture(nil,"OVERLAY")
    ring:SetAllPoints()
    ring:SetTexture("Interface\\Minimap\\MiniMap-TrackingBorder")
    ring:SetTexCoord(0,.6,0,.6)
    local function position()
        local a=math.rad(A.db.minimapAngle or 210)
        b:ClearAllPoints()
        b:SetPoint("CENTER",Minimap,"CENTER",math.cos(a)*(Minimap:GetWidth()/2+8),math.sin(a)*(Minimap:GetHeight()/2+8))
    end
    b:RegisterForClicks("LeftButtonUp","RightButtonUp")
    b:RegisterForDrag("LeftButton")
    b:SetScript("OnDragStart",function()
        b:SetScript("OnUpdate",function()
            local x,y=GetCursorPosition()
            local mx,my=Minimap:GetCenter()
            local scale=Minimap:GetEffectiveScale()
            A.db.minimapAngle=math.deg(math.atan2(y/scale-my,x/scale-mx))
            position()
        end)
    end)
    b:SetScript("OnDragStop",function() b:SetScript("OnUpdate",nil) end)
    b:SetScript("OnClick",function(_,button)
        if button=="RightButton" then RaynnaModsSettingsRegistry:Open("raynnanameplates")
        else A.TogglePreview() end
    end)
    b:SetScript("OnEnter",function()
        GameTooltip:SetOwner(b,"ANCHOR_LEFT")
        GameTooltip:SetText("Raynna's Nameplates")
        GameTooltip:AddLine("Left-click: show / hide previews\nRight-click: settings\nDrag: move button",1,1,1)
        GameTooltip:Show()
    end)
    b:SetScript("OnLeave",function() GameTooltip:Hide() end)
    position()
    if A.db.minimap==nil then A.db.minimap=true end
    b:SetShown(A.db.minimap)
end
